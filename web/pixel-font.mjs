const ACCENTS = {
  '̀': ['#.|.#'],
  '́': ['.#|#.'],
  '̂': ['.#.|#.#'],
  '̃': ['.#.#|#.#.'],
  '̈': ['#.#'],
  '̊': ['.#.|#.#|.#.'],
};
const CEDILLA = ['.#|..#|##.'];
const SAME_AS = { ' ': ' ', ' ': ' ', ' ': ' ', '‐': '-', '‑': '-' };
const DOTLESS = { i: 'ı', j: 'ȷ' };

const cache = new Map();

function plainGlyph(character) {
  const source = GLYPHS[SAME_AS[character] ?? character];
  if (!source) return null;
  const [text, descent = 0] = source;
  const rows = text === '' ? [] : text.split('|');
  const width = text === '' ? 1 : rows[0].length;
  return { character, rows, width, descent };
}

// Accents go on top of the plain letter, so that every language's letters match.
function accentedGlyph(character) {
  const [baseLetter, mark, ...more] = character.normalize('NFD');
  if (!mark || more.length) return null;
  const base = plainGlyph(DOTLESS[baseLetter] ?? baseLetter);
  if (!base) return null;
  if (mark === '̧') {
    const tail = CEDILLA[0].split('|');
    const left = (base.width - tail[0].length) >> 1;
    const rows = [
      ...base.rows,
      ...tail.map((row) =>
        row
          .padStart(left + row.length, '.')
          .padEnd(base.width, '.')
          .slice(0, base.width),
      ),
    ];
    return { character, rows, width: base.width, descent: tail.length };
  }
  if (!ACCENTS[mark]) return null;
  const accent = ACCENTS[mark][0].split('|');
  const left = (base.width - accent[0].length) >> 1;
  const padded = accent.map((row) => row.padStart(Math.max(left, 0) + row.length, '.').padEnd(base.width, '.'));
  const width = Math.max(base.width, padded[0].length);
  const rows = [
    ...padded,
    ...Array(ACCENT_GAP).fill('.'.repeat(width)),
    ...base.rows.map((row) => row.padEnd(width, '.')),
  ];
  return { character, rows, width, descent: base.descent };
}

// A glyph's rows and metrics, or null for anything this font doesn't have.
export function pixelFontGlyph(character) {
  if (cache.has(character)) return cache.get(character);
  const found = plainGlyph(character) ?? accentedGlyph(character);
  const base = found && (character.normalize('NFD')[0] ?? character);
  const glyph = found && {
    ...found,
    left: TIGHT_BOTH.has(base) ? 0 : 1,
    right: OVERHANG_RIGHT.has(base) ? -1 : TIGHT_BOTH.has(base) || TIGHT_RIGHT.has(base) ? 0 : 1,
  };
  cache.set(character, glyph);
  return glyph;
}

